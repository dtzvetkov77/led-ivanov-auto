const ALL_MAKE_WORDS = Object.values(MAKE_WORDS).flat()

function build(b: Brand): CategoryPageConfig {
  const body = [
    `## Какви LED крушки трябват за ${b.name}`,
    b.intro,
    `## LED крушки по модел ${b.name}`,
    `Най-честите фабрични конфигурации при халогенни фарове. Фаровете се различават според година, фейслифт и ниво на оборудване, затова винаги проверете надписа върху основата на старата крушка или ни пишете марка, модел и година.`,
    b.models.map(m => `- ${m}`).join('\n'),
    `## Особености при ${b.name}`,
    b.notes,
    `## CANBUS, преходници и ксенон`,
    [
      `- **Чувствителност към CANBUS:** ${b.canbus}. Повечето наши LED крушки имат вграден CANBUS. При грешка или мигане се добавя [CANBUS модул](/c/led-krushki-canbus). Повече в [Какво е CANBUS](/blog/kakvo-e-canbus-led-krushki).`,
      `- **Преходници:** ${b.adapters} Вижте [кога трябва преходник](/blog/prehodnici-za-led-krushki).`,
      `- **Фабричен ксенон:** ${b.xenon} За тях има [LED заместител на ксенон](/c/ksenon-krushki).`,
    ].join('\n'),
    `## Монтаж в София и доставка в цялата страна`,
    `В сервиза на LED Ivanov Auto в ж.к. Малинова долина, ул. „Георги Русев" 2, монтираме LED крушки на ${b.name}, проверяваме за грешки и [регулираме фаровете](/services/headlight-alignment) с уред. Работим всеки ден от 09:00 до 23:00. Ако не сте в София, поръчайте онлайн с доставка с Еконт или Спиди за 1–2 работни дни и монтирайте по [ръководството за монтаж](/blog/montazh-led-krushki-h7). Не сте сигурни коя крушка ви трябва? Обадете се на ${PHONE}.`,
    `Вижте и [LED крушки за други марки](/c/led-krushki-po-marka) и пълното ръководство [LED крушки за кола](/c/led-krushki-za-kola).`,
  ].join('\n\n')

  return {
    title: `LED Крушки за ${b.name} — ${b.bases} | LED Ivanov Auto`,
    metaDescription: `LED крушки за ${b.name}: какъв цокъл е вашият модел (${b.bases}), нужен ли е преходник и CANBUS. Монтаж в София, до 2 г. гаранция, доставка 1–2 дни.`,
    h1: `LED Крушки за ${b.name}`,
    breadcrumb: `LED Крушки за ${b.name}`,
    searchTerms: [...b.bases.split(', '), ...(b.searchExtra ?? [])],
    brandFilter: { ownMake: MAKE_WORDS[b.slug] ?? [b.name], anyMake: ALL_MAKE_WORDS },
    body,
    faq: b.faq,
  }
}

