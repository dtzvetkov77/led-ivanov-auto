import type { CategoryPageConfig } from './categoryPages'

// Landing pages "LED крушки за <марка>" served under /c/led-krushki-za-<brand>.
// Bulb data is the most common factory setup for halogen headlights; versions
// differ, so every page tells the reader to check the old bulb or call.

type Brand = {
  slug: string
  name: string
  // Short list of bases shown in the title, e.g. 'H7, H15, D3S'
  bases: string
  intro: string
  models: string[]
  notes: string
  canbus: 'ниска' | 'ниска до средна' | 'средна' | 'средна до висока' | 'висока'
  adapters: string
  xenon: string
  searchExtra?: string[]
  faq: { q: string; a: string }[]
}

